function frozenCatalog(locale, messages) {
  const keys = Object.keys(messages);
  if (
    keys.length !== EXPECTED_KEYS.length ||
    keys.some((key) => !EXPECTED_KEYS.includes(key)) ||
    EXPECTED_KEYS.some((key) => !Object.hasOwn(messages, key))
  ) {
    throw new TypeError(`Invalid ${locale} minority localization catalog.`);
  }
  return Object.freeze(messages);
}

