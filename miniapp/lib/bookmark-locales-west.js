const resolved = Object.fromEntries(
  Object.entries(TRANSLATIONS).map(([locale, values]) => {
    if (values.length !== KEYS.length) {
      throw new RangeError(
        `${locale} locale has ${values.length} values; expected ${KEYS.length}.`,
      );
    }
    return [
      locale,
      Object.freeze(Object.fromEntries(KEYS.map((key, index) => [key, values[index]]))),
    ];
  }),
);

export const BOOKMARK_LOCALE_EXTENSION = Object.freeze(resolved);
