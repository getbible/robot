function frozenCatalog(locale, messages) {
  const keys = Object.keys(messages);
  if (
    keys.length !== EXPECTED_KEYS.length ||
    keys.some((key) => !EXPECTED_KEYS.includes(key)) ||
    EXPECTED_KEYS.some((key) => !Object.hasOwn(messages, key))
  ) {
    throw new TypeError(`Invalid ${locale} bookmark localization catalog.`);
  }
  return Object.freeze(messages);
}

function frozenValuesCatalog(locale, values) {
  if (values.length !== EXPECTED_KEYS.length) {
    throw new TypeError(`Invalid ${locale} bookmark localization value count.`);
  }
  return frozenCatalog(locale, Object.fromEntries(
    EXPECTED_KEYS.map((key, index) => [key, values[index]]),
  ));
}

